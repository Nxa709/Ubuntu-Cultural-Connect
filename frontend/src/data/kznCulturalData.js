export function getKznItemsByCategory(categorySlug) {
  const cat = kznCategories.find(c => c.slug === categorySlug)
  return cat ? cat.items : []
}

export function getKznCategory(slug) {
  return kznCategories.find(c => c.slug === slug)
}

export function getAllKznItems() {
  return kznCategories.flatMap(c => c.items.map(item => ({ ...item, category: c.name, categorySlug: c.slug })))
}
