/* Returns { url, official } for an experience, or null if it has no title.
   Official sites come from the map above; everything else falls back to a
   web search so every hotspot still has a working link. */
export function getHotspotWebsite(exp) {
  if (!exp) return null
  const official = hotspotWebsites[exp.id]
  if (official) return { url: official, official: true }
  if (exp.title) {
    const q = [exp.title, exp.location, 'South Africa'].filter(Boolean).join(', ')
    return { url: `https://www.google.com/search?q=${encodeURIComponent(q)}`, official: false }
  }
  return null
}

export default hotspotWebsites
